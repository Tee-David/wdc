import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { validSignature, sameOrigin, futureStart, validZone, safeJoinUrl } from "../lib/meetings/policy.ts";
const body='{"booking":"fixture"}',secret="test-only-secret";
const signature=createHmac("sha256",secret).update(body).digest("hex");
assert.equal(validSignature(body,signature,secret),true);
assert.equal(validSignature(body+" ",signature,secret),false);
assert.equal(validSignature(body,null,secret),false);
assert.equal(validSignature(body,signature,undefined),false);
assert.equal(sameOrigin(null,"https://example.com"),false);
assert.equal(sameOrigin("https://evil.example","https://example.com"),false);
assert.equal(sameOrigin("https://example.com","https://example.com"),true);
assert.equal(futureStart(new Date(Date.now()+3600000).toISOString()),true);
assert.equal(futureStart(new Date(Date.now()-1).toISOString()),false);
assert.equal(validZone("Africa/Lagos"),true);
assert.equal(validZone("invalid-zone"),false);
assert.equal(safeJoinUrl("javascript:alert(1)"),null);
assert.equal(safeJoinUrl("https://user:password@example.com"),null);
console.log("Meetings trust-boundary checks passed");
