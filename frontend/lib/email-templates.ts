/**
 * The signature and legal tail of the text part.
 *
 * The plain text carries the same footer the HTML does, because for a reader
 * on a text-only client it IS the message -- and an unsubscribe offered only
 * to people whose client renders HTML is not an unsubscribe.
 */
function textShell(body: string, options: { unsubscribe?: boolean } = {}) {
  const tail = [
    "",
    "--",
    "We Dig Creativity",
    SITE_URL.replace(/^https?:\/\//, ""),
    CONTACT_EMAIL,
    LOCATION,
    "",
    LEGAL_LINE,
  ];
  if (options.unsubscribe) {
    tail.push(
      "",
      "You are receiving this because you contacted We Dig Creativity or are",
      `working with us on a project. To stop these messages, reply to ${CONTACT_EMAIL}`,
      "with the word unsubscribe.",
    );
  }
  return `${body.trim()}\n${tail.join("\n")}\n`;
}

