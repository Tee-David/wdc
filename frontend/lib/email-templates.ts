/* ---------------------------------------------------------------- escaping */

/**
 * Everything interpolated into an HTML part goes through this.
 *
 * It lives here rather than in lib/email.ts because this is the module that
 * builds HTML; lib/email.ts re-exports it so its existing call sites are
 * unchanged. A client's company name is attacker-supplied text as surely as
 * anything on the web is -- somebody typed it into a form.
 */
export function escapeHtml(value: string) {
  return value.replace(/[&<>"']/g, (char) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#039;",
  })[char]!);
}

/**
 * A URL is only allowed into an `href` if it is one we could have made.
 *
 * `javascript:` in an anchor is mostly a browser problem rather than a mail
 * one, but these builders are also what the admin will preview in a browser,
 * and a rejected link that renders as our own site is a better failure than a
 * link that runs something.
 */
function resolveUrl(value: string) {
  return /^https?:\/\//i.test(value) ? value : SITE_URL;
}

function safeUrl(value: string) {
  return escapeHtml(resolveUrl(value));
}

/* -------------------------------------------------------------- formatting */

/**
 * One day, one spelling, one timezone.
 *
 * Lagos explicitly: a due date rendered from the server's own clock says the
 * 14th to a reader in Lagos and the 13th to the same invoice opened from a US
 * region, and an invoice that disagrees with itself about its due date is an
 * invoice somebody argues about.
 */
export function emailDate(value: Date) {
  return new Intl.DateTimeFormat("en-GB", {
    day: "numeric", month: "long", year: "numeric", timeZone: "Africa/Lagos",
  }).format(value);
}

function emailDateTime(value: Date) {
  return new Intl.DateTimeFormat("en-GB", {
    day: "numeric", month: "long", year: "numeric",
    hour: "2-digit", minute: "2-digit", timeZone: "Africa/Lagos",
  }).format(value);
}

