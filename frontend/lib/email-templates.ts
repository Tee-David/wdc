/**
 * THE TRANSACTIONAL EMAIL SET.
 *
 * Ten messages over one shell, so the studio's mail looks like one company
 * rather than ten afternoons. Every builder returns a complete `Email` --
 * subject, plain text, full HTML document -- and nothing here sends anything:
 * `sendMail()` in lib/email.ts is the only thing that talks to a mail server,
 * and every one of these is composed before it is called.
 *
 * WHY TABLES AND INLINE STYLES, in 2026. Outlook on Windows still renders mail
 * through Word's HTML engine, which has no flexbox, no grid, no `max-width`
 * worth the name and drops most of a `<style>` block. A table with widths on
 * the cells is the only layout every client agrees about. The `<style>` block
 * that IS here carries one media query for phones and nothing load-bearing:
 * remove it and the mail still reads.
 *
 * WHY A FULL DOCUMENT AND NOT A `<div>`. Every message this project sent
 * before this file existed was a bare `<div>`. A fragment has no charset, no
 * language, no viewport and no title, so Gmail guesses the encoding, iOS
 * shrinks the whole thing to fit a 980px page, and a screen reader announces
 * the message with no name. Filters also score a document-shaped message above
 * a fragment, which matters here more than usual -- see
 * plans/email-deliverability.md for why our reputation has no slack in it.
 *
 * WHY THE PLAIN TEXT IS WRITTEN, NOT STRIPPED. A `text` part generated by
 * pulling the tags off the HTML reads like a ransom note and every filter
 * knows what one looks like; a missing one is worse still, because Gmail
 * treats HTML-only mail as a bulk signal. So each message below writes its
 * text part as prose -- the same message, said the way you would say it in a
 * plain reply -- and it is the version a watch, a screen reader and a
 * text-only client actually get.
 *
 * WHY THE BUTTON IS A DEEPER ORANGE THAN THE LOGO. The label is white, and
 * white on #ff6500 measures 2.95:1, which fails AA. #c95000 is the site's own
 * `--accent-ink`, the orange it already uses wherever orange has to be read,
 * and white on it is 4.53:1. Pinned by tests/email-templates.spec.ts.
 *
 * NO `server-only` HERE ON PURPOSE. This module builds strings: it holds no
 * credential, opens no connection and reads no environment beyond the public
 * site URL. Leaving the guard off is what lets the spec import it directly and
 * assert on the real output rather than on a copy of it.
 */

